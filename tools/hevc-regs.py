#!/usr/bin/env python3
"""Generate tvos/video/hevc/hevc_regs.h: the HEVC registers a source file names, as DOS word indexes, from Amlogic's
dos_registers_v1.h and vh265.c with s7_mm_registers_compat applied.

Usage: hevc-regs.py [--out HEADER] [--vp9] SOURCE.c... (run from the repository's top; default
tvos/video/hevc/hevc_regs.h). --vp9: VP9's own names too, the scratch registers' aliases taken from vvp9.c first.
"""
import re
import sys

BASE = 'work/src/media_modules-aml/drivers/'


def main():
    args = sys.argv[1:]
    out_path = 'tvos/video/hevc/hevc_regs.h'
    if args[:1] == ['--out']:
        out_path, args = args[1], args[2:]
    vp9 = args[:1] == ['--vp9']
    if vp9:
        args = args[1:]
    src = ''.join(open(p).read() for p in args)
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'//.*', '', src)
    src = re.sub(r'"(\\.|[^"\\])*"', '""', src)
    names = sorted(set(re.findall(r'\b((?:HEVC|HEVCD|DOS|NAL_SEARCH|DEBUG|LMEM|DECODE|VP9|VP9D)_[A-Za-z0-9_]+)\b', src)))
    names = [n for n in names if n not in ('HEVC_CONFIG_LITTLE_ENDIAN', 'HEVC_REGS_H', 'HEVC_SLICES') and
             not n.startswith(('VP9_PROB_', 'VP9_COUNT_', 'VP9_RPM', 'VP9_REGS')) or n in ('VP9_PROB_SWAP_BUFFER', 'VP9_COUNT_SWAP_BUFFER')]
    defs = {}
    codecs = ['vp9/vvp9.c', 'h265/vh265.c'] if vp9 else ['h265/vh265.c']
    for path in [BASE + 'include/regs/dos_registers_v1.h'] + [BASE + 'frame_provider/decoder/' + c for c in codecs]:
        text = open(path, errors='replace').read()
        for m in re.finditer(r'^#define\s+(\w+)\s+(.+?)\s*(?:/\*.*)?$', text, re.M):
            defs.setdefault(m.group(1), m.group(2).strip())

    def resolve(n):
        v = defs.get(n)
        if v is None:
            raise SystemExit('unknown ' + n)
        v = re.sub(r'\s*\|\s*MASK_S\d_NEW_REGS', '', v.split('//')[0]).strip('() ')
        if re.fullmatch(r'0x[0-9a-fA-F]+', v):
            return int(v, 16)
        if re.fullmatch(r'\w+', v):
            return resolve(v)
        raise SystemExit(f'cannot resolve {n} = {v}')

    crc, acp = resolve('HEVC_STREAM_CRC'), resolve('VP9_ACP_CTRL')
    out = ['/* HEVC core registers (DOS word indexes), from Amlogic dos_registers_v1.h and vh265.c with',
           ' * s7_mm_registers_compat applied. Generated by tools/hevc-regs.py. */',
           '#ifndef HEVC_REGS_H', '#define HEVC_REGS_H']
    for n in names:
        a = resolve(n)
        if n == 'HEVC_SLICE_DATA_CTL':
            a += 3
        elif crc <= a <= acp:
            a -= 2
        out.append(f'#define {n:<40} 0x{a:04x}')
    out.append('#endif')
    open(out_path, 'w').write('\n'.join(out) + '\n')
    print(f'{len(names)} registers')


if __name__ == '__main__':
    main()
